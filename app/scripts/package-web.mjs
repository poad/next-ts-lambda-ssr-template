import { createHash } from 'node:crypto';
// Lambda Web Functions 用のパッケージングスクリプト
// `next build` の standalone 出力を .web-package/ に組み立てる
// - .next/standalone 配下を丸ごとコピー (monorepo では server.js が app/ 等にネストされる)
// - public/ と .next/static/ を server.js と同じ階層に配置 (Next.js standalone の定石)
// - AWS_LAMBDA_HTTP_ENDPOINT を PORT/HOSTNAME に変換する index.js を zip ルートに生成
import {
  cpSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const appDir = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const standaloneDir = path.join(appDir, '.next', 'standalone');
const outDir = path.join(appDir, '.web-package');

function findServerFile(dir, depth) {
  for (const entry of readdirSync(dir)) {
    const full = path.join(dir, entry);
    if (entry === 'server.js' && statSync(full).isFile()) return full;
    if (depth > 0 && statSync(full).isDirectory() && entry === 'node_modules') continue;
    if (depth > 0 && statSync(full).isDirectory()) {
      const found = findServerFile(full, depth - 1);
      if (found) return found;
    }
  }
  return undefined;
}

if (!existsSync(standaloneDir)) {
  console.error('error: .next/standalone がありません。先に `next build` を実行してください。');
  process.exit(1);
}

const serverFile = findServerFile(standaloneDir, 3);
if (!serverFile) {
  console.error('error: .next/standalone 配下に server.js が見つかりません。');
  process.exit(1);
}
const serverDir = path.dirname(path.relative(standaloneDir, serverFile));
const serverPosix = serverDir === '' ? '.' : serverDir.split(path.sep).join(path.posix.sep);
console.log(`server.js: ${path.relative(appDir, serverFile)}`);

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

// standalone 出力を丸ごとコピー
cpSync(standaloneDir, outDir, { recursive: true });

const serverOutDir = path.join(outDir, serverDir);
// public/ を server.js と同じ階層へ
const publicDir = path.join(appDir, 'public');
if (existsSync(publicDir)) {
  cpSync(publicDir, path.join(serverOutDir, 'public'), { recursive: true });
}
// .next/static を server.js と同じ階層の .next 配下へ
const staticDir = path.join(appDir, '.next', 'static');
if (existsSync(staticDir)) {
  cpSync(staticDir, path.join(serverOutDir, '.next', 'static'), { recursive: true });
}

// Web Functions のエントリーファイル (ランタイムはデフォルトで zip ルートの index.js を読み込む)
const importPath = serverPosix === '.' ? './server.js' : `./${serverPosix}/server.js`;
writeFileSync(
  path.join(outDir, 'index.js'),
  `// auto-generated by scripts/package-web.mjs (Lambda Web Functions entrypoint)
// Next.js standalone server は PORT/HOSTNAME を読むため AWS_LAMBDA_HTTP_ENDPOINT から変換する
const endpoint = process.env.AWS_LAMBDA_HTTP_ENDPOINT ?? '127.0.0.1:3000';
const separator = endpoint.lastIndexOf(':');
process.env.HOSTNAME = endpoint.slice(0, separator);
process.env.PORT = endpoint.slice(separator + 1);
await import('${importPath}');
`,
);

// CDK が Revision の置換検知に使うコンテンツハッシュ (.web-package 全体)
function hashDirectory(dir, hash) {
  for (const entry of readdirSync(dir).sort()) {
    const full = path.join(dir, entry);
    const stat = statSync(full);
    if (stat.isDirectory()) {
      hashDirectory(full, hash);
    } else if (stat.isFile()) {
      hash.update(path.relative(outDir, full));
      hash.update(readFileSync(full));
    }
  }
}
const packageHash = createHash('sha256');
hashDirectory(outDir, packageHash);
writeFileSync(path.join(outDir, '.package-hash'), `${packageHash.digest('hex')}\n`);

// ネイティブ依存の注意喚起 (Web Functions は Arm64 固定)
console.log(`package dir: ${path.relative(appDir, outDir)}/ (entry: index.js -> ${importPath})`);
console.log('done. local test: AWS_LAMBDA_HTTP_ENDPOINT=127.0.0.1:3000 node .web-package/index.js');
